# -*- coding: utf-8 -*-
"""
实验10.1.3（1）：单样本双侧 t 检验
- 检验数据集的总体均值是否与给定值（mu0=0）存在显著差异
- 分别使用临界值法和 p 值法两种方式作出判断
"""

import numpy as np              # 数值计算，提供 mean、std 等函数
from scipy.stats import t       # 统计学：t 分布的概率密度函数(CDF)、分位数(PPF)

# ======================== 1. 设定参数与输入数据 ========================

alpha = 0.05                    # 显著性水平，犯第一类错误的概率上限（5%）
data = [6, 8, 4, 6, -3, 7, 2, 6, -2, -1]   # 样本观测值（n=10）

# ======================== 2. 计算样本统计量 ========================

m = np.mean(data)               # 样本均值 x̄
s = np.std(data, ddof=1)        # 样本标准差 s（ddof=1 表示除以 n-1，得到无偏估计）

print('样本平均值 =', m)         # 输出：3.3
print('样本标准差 =', s)         # 输出：约 4.08

# ======================== 3. 设定原假设与备择假设 ========================
# H0: μ = 0   （总体均值等于 0）
# H1: μ ≠ 0   （总体均值不等于 0，双侧检验）

mu0 = 0                         # 原假设中待检验的总体均值

# ======================== 4. 临界值法（拒绝域法） ========================

n = len(data)                   # 样本容量 n = 10

# 计算 t 分布的右侧分位数 t_{1-α/2}(n-1)
# 即 P(T > t1) = α/2 = 0.025，自由度 df = n - 1 = 9
t1 = t.ppf(1 - alpha / 2, df=n - 1)

# 计算检验统计量（t 统计量）
# 公式：t = (x̄ - μ0) / (s / √n) = (x̄ - μ0) * √n / s
c = (m - mu0) * np.sqrt(n) / s

print('t值 =', c, '  分位数 =', t1)

# 决策：若 |t| < t_{1-α/2}，落入接受域，接受 H0；否则拒绝 H0
if abs(c) < t1:
    print('接受原假设（临界值法）：样本均值与 0 无显著差异')
else:
    print('拒绝原假设（临界值法）：样本均值与 0 有显著差异')

# ======================== 5. p 值法 ========================

# 计算双侧检验的 p 值
# p = 2 * P(T > |t|)，其中 T ~ t(n-1)
# t.cdf(|c|, n-1) 返回 P(T ≤ |c|)，因此 1 - cdf 得到右侧尾部概率
p = 2 * (1 - t.cdf(abs(c), n - 1))

print('检验的 p 值为', p)

# 决策：若 p > α，接受 H0；否则拒绝 H0
if p > alpha:
    print('接受原假设（p 值法）：样本均值与 0 无显著差异')
else:
    print('拒绝原假设（p 值法）：样本均值与 0 有显著差异')
